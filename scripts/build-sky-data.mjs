/**
 * Builds the compact sky assets the hero loads at runtime:
 *   public/sky/stars.bin           naked-eye stars (HYG v3.7), sorted brightest first
 *   public/sky/lines.bin           constellation stick figures (d3-celestial)
 *   public/sky/milkyway.webp       Milky Way brightness, equirectangular in J2000 RA/Dec
 *   src/sky/constellations.gen.ts  constellation names/centres for labels
 *
 * Run: npm run sky:data   (re-run only if the source catalogues change)
 * Sources & licences: HYG (CC BY-SA, astronexus), d3-celestial (BSD-3, Olaf Frohn).
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { geoEquirectangular, geoPath } from 'd3-geo'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dataDir = path.join(root, 'scripts/data')
const outDir = path.join(root, 'public/sky')
fs.mkdirSync(outDir, { recursive: true })

const MAG_LIMIT = 6.5 // naked-eye limit under a dark rural sky
const HYG_URL = 'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/v3/hyg_v37.csv.gz'

// ---------- Stars ----------
async function loadHyg() {
  const file = path.join(dataDir, 'hyg_v37.csv.gz')
  if (!fs.existsSync(file)) {
    console.log('Downloading HYG v3.7 …')
    const res = await fetch(HYG_URL)
    if (!res.ok) throw new Error(`HYG download failed: HTTP ${res.status} from ${HYG_URL}`)
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()))
  }
  return zlib.gunzipSync(fs.readFileSync(file)).toString('utf8')
}

function parseCsv(text) {
  const lines = text.split('\n')
  const header = lines[0].split(',')
  const idx = (k) => {
    const i = header.indexOf(k)
    if (i < 0) throw new Error(`HYG: column "${k}" missing; the catalogue format changed`)
    return i
  }
  const I = { ra: idx('ra'), dec: idx('dec'), mag: idx('mag'), ci: idx('ci'), proper: idx('proper'), id: idx('id') }
  const rows = []
  for (let n = 1; n < lines.length; n++) {
    if (!lines[n]) continue
    // HYG has no quoted commas in the columns we read, so a plain split is safe.
    const c = lines[n].split(',')
    if (c[I.id] === '0') continue // Sol
    const mag = parseFloat(c[I.mag])
    if (!(mag <= MAG_LIMIT)) continue
    rows.push({ ra: parseFloat(c[I.ra]), dec: parseFloat(c[I.dec]), mag, bv: c[I.ci] === '' ? 0.65 : parseFloat(c[I.ci]), name: c[I.proper] })
  }
  rows.sort((a, b) => a.mag - b.mag)
  return rows
}

function writeStars(rows) {
  // 8 bytes/star: uint16 RA (0..24h), int16 Dec (±90°), int16 mag×1000, int16 B–V×1000
  const buf = Buffer.alloc(8 + rows.length * 8)
  buf.write('ASC1', 0, 'ascii')
  buf.writeUInt32LE(rows.length, 4)
  rows.forEach((s, i) => {
    const o = 8 + i * 8
    buf.writeUInt16LE(Math.round((s.ra / 24) * 65535) % 65536, o)
    buf.writeInt16LE(Math.round((s.dec / 90) * 32767), o + 2)
    buf.writeInt16LE(Math.round(s.mag * 1000), o + 4)
    buf.writeInt16LE(Math.round(Math.max(-0.4, Math.min(2.0, s.bv)) * 1000), o + 6)
  })
  fs.writeFileSync(path.join(outDir, 'stars.bin'), buf)
  const tiers = [4.5, 5.5, 6.5].map((m) => `≤${m}: ${rows.filter((r) => r.mag <= m).length}`)
  console.log(`stars.bin  ${rows.length} stars (${tiers.join(', ')}), ${buf.length} bytes`)
}

// ---------- Constellation lines ----------
function writeLines() {
  const lines = JSON.parse(fs.readFileSync(path.join(dataDir, 'constellations.lines.json'), 'utf8'))
  const meta = JSON.parse(fs.readFileSync(path.join(dataDir, 'constellations.json'), 'utf8'))
  const names = new Map(meta.features.map((f) => [f.id, { name: f.properties.name, centre: f.geometry.coordinates }]))
  const verts = [] // per vertex: x, y, z (J2000 unit), along (0..1 within constellation), constellation index
  const cons = []
  lines.features.forEach((f) => {
    const ci = cons.length
    const m = names.get(f.id)
    if (!m) throw new Error(`constellations.json lacks metadata for ${f.id}`)
    cons.push({ id: f.id, name: m.name, ra: (m.centre[0] + 360) % 360, dec: m.centre[1] })
    const segs = []
    for (const poly of f.geometry.coordinates)
      for (let k = 0; k < poly.length - 1; k++) segs.push([poly[k], poly[k + 1]])
    const n = segs.length
    segs.forEach(([a, b], k) => {
      for (const [p, t] of [[a, k / n], [b, (k + 1) / n]]) {
        const ra = (p[0] * Math.PI) / 180, dec = (p[1] * Math.PI) / 180
        verts.push(Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec), t, ci)
      }
    })
  })
  const f32 = new Float32Array(verts)
  fs.writeFileSync(path.join(outDir, 'lines.bin'), Buffer.from(f32.buffer))
  console.log(`lines.bin  ${f32.length / 5} vertices, ${cons.length} constellations, ${f32.byteLength} bytes`)
  const ts =
    '// Generated by scripts/build-sky-data.mjs. Do not edit.\n' +
    '// Source: d3-celestial (BSD-3-Clause, Olaf Frohn). RA/Dec in degrees, J2000.\n' +
    `export const CONSTELLATIONS: ReadonlyArray<{ id: string; name: string; ra: number; dec: number }> = ${JSON.stringify(
      cons.map((c) => ({ ...c, ra: +c.ra.toFixed(2), dec: +c.dec.toFixed(2) })),
    )}\n`
  fs.writeFileSync(path.join(root, 'src/sky/constellations.gen.ts'), ts)
}

// ---------- Milky Way texture ----------
async function writeMilkyWay() {
  const W = 2048, H = 1024
  const mw = JSON.parse(fs.readFileSync(path.join(dataDir, 'mw.json'), 'utf8'))
  // Equirectangular: x = (RA_signed + 180°)/360°·W, y = (90° − Dec)/180°·H. Matches the shader's lookup.
  const projection = geoEquirectangular().scale(W / (2 * Math.PI)).translate([W / 2, H / 2]).precision(0.1)
  const pathGen = geoPath(projection)
  // d3-celestial uses RA as longitude with the sky's handedness; project RA as −lon would mirror it,
  // so we keep RA as longitude and mirror nothing: the shader samples with the same convention.
  const levels = mw.features.filter((f) => /^ol\d$/.test(f.id)).sort((a, b) => a.id.localeCompare(b.id))
  if (levels.length !== 5) throw new Error(`mw.json: expected 5 outline levels, found ${levels.length}`)
  const paths = levels
    .map((f, i) => `<path d="${pathGen(f)}" fill="#fff" fill-opacity="${[0.16, 0.2, 0.22, 0.24, 0.26][i]}"/>`)
    .join('')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}"><rect width="100%" height="100%" fill="#000"/>${paths}</svg>`
  // Blur soft contours into diffuse light; then downsample: the sky shader adds fine noise on top.
  const img = await sharp(Buffer.from(svg)).blur(4).greyscale()
  await img.clone().webp({ quality: 82 }).toFile(path.join(outDir, 'milkyway.webp'))
  await img.clone().png().toFile(path.join(root, 'research/milkyway-preview.png'))
  const { size } = fs.statSync(path.join(outDir, 'milkyway.webp'))
  console.log(`milkyway.webp  2048×1024, ${size} bytes`)
}

const rows = parseCsv(await loadHyg())
writeStars(rows)
writeLines()
await writeMilkyWay()
